package com.project.autoscaling.simulation.dto;

import com.project.autoscaling.common.enums.WorkloadProfile;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class SimulationStatusResponse {

    @Schema(description = "Application ID")
    private Long applicationId;

    @Schema(description = "Application Name")
    private String applicationName;

    @Schema(description = "Whether the simulation is actively running")
    private boolean running;

    @Schema(description = "Active workload simulation profile")
    private WorkloadProfile profile;

    @Schema(description = "Interval in seconds between simulation ticks")
    private int intervalSeconds;

    @Schema(description = "Timestamp when simulation started")
    private LocalDateTime startedAt;

    @Schema(description = "Number of telemetry batches generated so far")
    private long metricsGeneratedCount;

    @Schema(description = "Timestamp of the most recently generated metric")
    private LocalDateTime lastGeneratedAt;

    @Schema(description = "Indicator that data generated by this process is simulated", example = "true")
    @Builder.Default
    private boolean simulated = true;
}
